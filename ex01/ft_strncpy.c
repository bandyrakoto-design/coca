#include <unistd.h>

char	*ft_strncpy(char *dest, char *src, unsigned int n)
{
	int	i;

	i = 0;
	while (src[i] != '\0' && i < n)
	{
		dest[i] = src[i];
		i++;
	}
	while (i < n)
	{
		dest[i] = '\0';
	}
	return (dest);
}

int main()
{
    char s1[]={"hello World"};
    char s2[]={"pain"};
    ft_strncpy(s1, s2, 2);
    write(1, &s1, 13);
}

