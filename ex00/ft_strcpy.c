#include <unistd.h>

char	*ft_strcpy(char *dest, char *src)
{
	int	i;

	i = 0;
	while (src[i])
	{
		dest[i] = src[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}

int main(void)
{
	char a [] = {"abc"};
	char b [] = {"efg"};
	ft_strcpy(a , b);
	write(1, &a, 3);
	return (0);
}
